using JLD2
export quicksave_aircraft, quickload_aircraft

"""
    quicksave_aircraft(ac::TASOPT.aircraft=TASOPT.read_aircraft_model(),
        filepath=joinpath(TASOPT.__TASOPTroot__, "IO/default_quicksave_aircraft.jld2"))

Serializes and saves aircraft `struct` to a .jld2 using JLD2 (not human-readable).
Intended to store aircraft models with ALL fields (since not everything is stored by save_aircraft_model).

!!! details "🔃 Inputs and Outputs"
    **Inputs:**
    - `ac::TASOPT.aircraft`: TASOPT aircraft `struct` containing model in any state. 
    - `filepath::String`: path and name of .jld2 file to be written.
    **Outputs:**
    - None.
"""
function quicksave_aircraft(ac::TASOPT.aircraft=TASOPT.read_aircraft_model(), 
    filepath=joinpath(TASOPT.__TASOPTroot__, "IO/default_quicksave_aircraft.jld2"))

    @save filepath ac
end

"""
    quickload_aircraft(filepath=joinpath(TASOPT.__TASOPTroot__, "IO/default_quicksave_aircraft.jld2"))

Reads a .jld2 file generated by `quicksave_aircraft()` and returns the generated `aircraft` structure.

Files saved before fields were added to `aircraft` can still be loaded; missing fields take their defaults.

!!! details "🔃 Inputs and Outputs"
    **Inputs:**
    - `filepath::String`: path and name of .jld2 file to be read.
    **Outputs:**
    - `ac::TASOPT.aircraft`: TASOPT aircraft `struct` with model in the state it was saved in.
"""
function quickload_aircraft(filepath=joinpath(TASOPT.__TASOPTroot__, "IO/default_quicksave_aircraft.jld2"))
    @load filepath ac
    return ac isa JLD2.ReconstructedMutable ? aircraft_from_reconstructed(ac) : ac
end

"""
    aircraft_from_reconstructed(rc::JLD2.ReconstructedMutable)

Builds an `aircraft` from the JLD2 placeholder returned when the saved fields differ from the current `aircraft`.
Fields absent from the file take their defaults.

!!! details "🔃 Inputs and Outputs"
    **Inputs:**
    - `rc::JLD2.ReconstructedMutable`: JLD2 reconstruction of a saved `aircraft`.
    **Outputs:**
    - `ac::TASOPT.aircraft`: TASOPT aircraft `struct` with the stored fields and default values for the others.
"""
function aircraft_from_reconstructed(rc::JLD2.ReconstructedMutable)
    stored_fields = Dict(name => getproperty(rc, name) for name in propertynames(rc))
    current_fields = fieldnames(aircraft)
    fields = Dict(name => value for (name, value) in stored_fields if name in current_fields)
    return aircraft{typeof(stored_fields[:wake_system])}(; fields...)
end
